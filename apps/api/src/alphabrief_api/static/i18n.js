export class I18n {
  constructor() {
    this.currentLang = this._detectLanguage();
  }

  _detectLanguage() {
    const saved = localStorage.getItem("alphabrief_lang");
    if (saved === "zh" || saved === "en") return saved;
    const navLang = navigator.language || "";
    return navLang.toLowerCase().startsWith("zh") ? "zh" : "en";
  }

  setLanguage(lang) {
    if (lang !== "zh" && lang !== "en") return;
    this.currentLang = lang;
    localStorage.setItem("alphabrief_lang", lang);
    document.documentElement.lang = lang;
  }

  getLanguage() {
    return this.currentLang;
  }

  t(path) {
    const keys = path.split(".");
    let cur = DICTIONARIES[this.currentLang];
    for (const k of keys) {
      if (cur && cur[k] !== undefined) {
        cur = cur[k];
      } else {
        // Fallback to English if missing in Chinese
        let fallback = DICTIONARIES.en;
        for (const fk of keys) {
          if (fallback && fallback[fk] !== undefined) fallback = fallback[fk];
          else return path;
        }
        return fallback;
      }
    }
    return cur;
  }
}

export const i18n = new I18n();
